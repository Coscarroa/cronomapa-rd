/**
 * Resuelve la cápsula de fuente primaria correspondiente a un año o identificador de época.
 */
export function getPrimarySourceForYearOrEpoch(yearOrEpoch) {
  if (typeof yearOrEpoch === 'string') {
    const key = yearOrEpoch.toLowerCase();
    if (key === '1492' || key === 'taina') return PRIMARY_SOURCES_BY_EPOCH['1492'];
    if (key === 'colonia') return PRIMARY_SOURCES_BY_EPOCH.colonia;
    if (key === '1844' || key === 'independencia') return PRIMARY_SOURCES_BY_EPOCH['1844'];
    if (key === 'restauracion') return PRIMARY_SOURCES_BY_EPOCH.restauracion;
    if (key === 'siglo_xx' || key === 'actualidad') return PRIMARY_SOURCES_BY_EPOCH.siglo_xx;
  }

  const year = Number(yearOrEpoch) || 2026;
  if (year <= 1504) return PRIMARY_SOURCES_BY_EPOCH['1492'];
  if (year <= 1821) return PRIMARY_SOURCES_BY_EPOCH.colonia;
  if (year <= 1862) return PRIMARY_SOURCES_BY_EPOCH['1844'];
  if (year <= 1915) return PRIMARY_SOURCES_BY_EPOCH.restauracion;
  return PRIMARY_SOURCES_BY_EPOCH.siglo_xx;
}
